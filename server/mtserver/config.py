"""Server configuration: listening address, advertised DC, RSA identity, dev mode.

On first run a 2048-bit RSA key pair is generated and stored in server_key.pem.
The corresponding public key + fingerprint must be embedded into the Android app
(see docs/CUSTOM_BACKEND.md) so the app trusts this server during the DH handshake.
"""
import os
import time

from .crypto import RSAKey

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # .../server
KEY_FILE = os.path.join(BASE_DIR, "server_key.pem")


class ServerConfig:
    def __init__(self, listen_host="0.0.0.0", listen_port=443,
                 public_host="127.0.0.1", public_port=443,
                 dc_id=1, dev_code=None, db_path=None):
        self.listen_host = listen_host
        self.listen_port = listen_port
        # what clients are told to dial (goes into help.getConfig dcOption)
        self.public_host = public_host
        self.public_port = public_port
        self.dc_id = dc_id
        # if set, this SMS code is always accepted (development mode)
        self.dev_code = dev_code
        self.db_path = db_path or os.path.join(BASE_DIR, "mtserver.db")
        self.files_dir = os.path.join(BASE_DIR, "files")
        os.makedirs(self.files_dir, exist_ok=True)

        if os.path.exists(KEY_FILE):
            with open(KEY_FILE, "rb") as f:
                self.rsa = RSAKey.load(f.read())
        else:
            self.rsa = RSAKey()
            with open(KEY_FILE, "wb") as f:
                f.write(self.rsa.private_pem())
            os.chmod(KEY_FILE, 0o600)

    @property
    def fingerprint(self) -> int:
        return self.rsa.fingerprint

    @property
    def public_key_pem(self) -> str:
        return self.rsa.public_pem().decode()

    def client_header_snippet(self) -> str:
        """Ready-to-paste content for TMessagesProj/jni/tgnet/CustomBackendConfig.h"""
        pem_lines = self.public_key_pem.strip().splitlines()
        pem_c = "\n".join(
            '    "%s\\n"' % line for line in pem_lines
        )
        return f"""// AUTO-GENERATED by the mtserver (server/) — paste into
// TMessagesProj/jni/tgnet/CustomBackendConfig.h
#pragma once
#define CUSTOM_BACKEND 1
#define CUSTOM_BACKEND_DC_ID {self.dc_id}
#define CUSTOM_BACKEND_HOST "{self.public_host}"
#define CUSTOM_BACKEND_PORT {self.public_port}
#define CUSTOM_BACKEND_RSA_FINGERPRINT 0x{self.fingerprint & 0xFFFFFFFFFFFFFFFF:016x}ULL
static const char *CUSTOM_BACKEND_RSA_PUBLIC_KEY_PEM =
{pem_c};
"""
